// The page's own words in English and Korean. English is the default; the page turns Korean when she
// writes to the guide in Korean, and the EN / 한국어 switch in the top bar turns it either way.
//
// Only the page's own words are here. Text that comes from the data (place names, quotes, a memory
// sentence that was saved in English only, an error from the agent) is shown as given, never translated here.
// A sentence without a Korean line below is shown in English.

let lang = "en";

export function setLang(value) {
  lang = value === "ko" ? "ko" : "en";
}

/** Runs `work` with the words in another language, for a text that is not in the page's own (the route note). */
export function inLang(value, work) {
  const before = lang;
  setLang(value);
  try { return work(); } finally { lang = before; }
}

/** She wrote Korean when the text has Hangul in it. */
export function isKorean(text) {
  return /[ᄀ-ᇿ㄰-㆏가-힣]/.test(String(text ?? ""));
}

/**
 * t("Stop {n} of {count}", { n: 1, count: 3 }): the sentence in the page's language, with the values filled in.
 * The same English words can need different Korean in two places; then the key carries a tag at its end,
 * "What I know [bar]", which is never shown.
 */
export function t(en, values = null) {
  const text = lang === "ko" && KO[en] ? KO[en] : en.replace(/ \[\w+\]$/, "");
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (all, key) => (key in values ? String(values[key]) : all));
}

